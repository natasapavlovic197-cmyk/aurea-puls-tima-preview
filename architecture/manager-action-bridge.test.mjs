import assert from 'node:assert/strict';
import {previewManagerAction,commitManagerAction} from './manager-action-bridge.mjs';
import {managerClient} from './manager-rpc-adapter.mjs';
const org='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const cycle='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
const calls=[];
const client={rpc:async(name,args)=>{calls.push({name,args});return {data:[{id:'test-action'}],error:null}}};
const manager=managerClient(client,org);
const recommendation={domain:'workload',itemCode:'A_WORKLOAD',itemVersion:1,title:'Preispitati opterećenje',requiresManagerJudgment:true,avoidsIndividualInference:true};
const accepted=previewManagerAction(recommendation,{decision:'accept',dueOn:'2026-12-07'});
assert.equal(calls.length,0,'Preview must never write');
const result=await commitManagerAction(manager,accepted,{cycleId:cycle});
assert.equal(result[0].id,'test-action');
assert.equal(calls.length,1);
assert.equal(calls[0].name,'aurea_manager_save_action');
assert.equal(calls[0].args.p_organization_id,org);
assert.equal(calls[0].args.p_cycle_id,cycle);
assert.equal(calls[0].args.p_due_on,'2026-12-07');
assert.equal(calls[0].args.p_status,'open');
const edited=previewManagerAction(recommendation,{decision:'edit',description:'Uskladiti prioritete na nedeljnom sastanku'});
await commitManagerAction(manager,edited);
assert.equal(calls.length,2);
const rejected=previewManagerAction(recommendation,{decision:'reject'});
await assert.rejects(()=>commitManagerAction(manager,rejected),/Unapproved/);
assert.equal(calls.length,2,'Reject must never write');
await assert.rejects(()=>commitManagerAction(manager,accepted,{cycleId:'invalid'}),/Invalid cycle/);
assert.equal(calls.length,2);
await assert.rejects(()=>commitManagerAction(null,accepted),/Authenticated/);
assert.equal(calls.length,2);
console.log('PASS: explicit preview/commit boundary, authenticated tenant RPC, reject no-write and validation');
