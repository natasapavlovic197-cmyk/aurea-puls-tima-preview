'use strict';
const assert=require('node:assert/strict');
const {anchors,rotation,domains,weeklyItems,validateBank}=require('./psychometric-item-bank.cjs');
assert.equal(validateBank(),true);
assert.equal(domains.length,10);
assert.equal(anchors.length,3);
assert.equal(rotation.length,4);
const monday=['2026-11-23','2026-11-30','2026-12-07','2026-12-14','2026-12-21'];
const batches=monday.map(weeklyItems);
assert.ok(batches.every(b=>b.length===6));
assert.deepEqual(batches[0].map(x=>x.code),batches[4].map(x=>x.code));
assert.deepEqual(batches[0].slice(0,3).map(x=>x.code),anchors.map(x=>x.code));
assert.ok(batches.every(b=>new Set(b.map(x=>x.code)).size===6));
assert.equal(new Set(batches.slice(0,4).flat().map(x=>x.domain)).size,10);
assert.deepEqual(weeklyItems('2026-11-16').slice(3).map(x=>x.code),rotation[3].map(x=>x.code));
assert.throws(()=>weeklyItems('2026-11-24'),/Monday/);
assert.throws(()=>weeklyItems('2026-02-30'),/Monday|Invalid/);
assert.throws(()=>weeklyItems('not-a-date'),/Invalid/);
console.log('PASS: six-item weekly candidate pulse, anchor stability, four-week rotation and ten-domain coverage');
