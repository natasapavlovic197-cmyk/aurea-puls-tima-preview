import assert from 'node:assert/strict';
import {createEmployeeRpcGateway} from './employee-rpc-gateway.mjs';
const hash='a'.repeat(64);
const answers=['J1','K1','O1','P1'].map(code=>({code,rating:5}));
const event=(action,extra={})=>({httpMethod:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({action,hash,...extra})});
const calls=[];
const client={async rpc(name,args){
 calls.push({name,args});
 if(name==='aurea_employee_invitation')return {data:{status:'ready',questions:answers.map((a,i)=>({code:a.code,wording:'Pitanje '+(i+1),position:i+1,email:'PRIVATE'}))},error:null};
 if(name==='aurea_employee_submit')return {data:{status:'submitted'},error:null};
 throw Error('Unexpected RPC');
}};
const h=createEmployeeRpcGateway({client,rateLimit:async()=>true});
const invitation=await h(event('invitation'));
assert.equal(invitation.statusCode,200);
assert.equal(invitation.body.includes('PRIVATE'),false);
assert.deepEqual(JSON.parse(invitation.body).questions.map(x=>x.code),['J1','K1','O1','P1']);
assert.equal((await h(event('submit',{answers:answers.map(a=>({...a,private:'never-send'}))}))).statusCode,400);
const submitted=await h(event('submit',{answers}));
assert.equal(submitted.statusCode,200);
assert.deepEqual(JSON.parse(submitted.body),{status:'submitted'});
assert.deepEqual(calls.map(c=>c.name),['aurea_employee_invitation','aurea_employee_submit']);
assert.equal(calls[0].args.p_hash,hash);
assert.equal(calls[1].args.p_hash,hash);
assert.equal(JSON.stringify(calls[1].args).includes('never-send'),false);
assert.equal((await createEmployeeRpcGateway({client,rateLimit:async()=>false})(event('invitation'))).statusCode,429);
assert.equal((await h(event('submit',{answers:[answers[0],answers[0],...answers.slice(2)]}))).statusCode,400);
assert.equal(calls.length,2);
assert.throws(()=>createEmployeeRpcGateway({client}),TypeError);
assert.throws(()=>createEmployeeRpcGateway({rateLimit:async()=>true}),TypeError);
const failed=createEmployeeRpcGateway({client:{rpc:async()=>({error:{message:'secret database error'}})},rateLimit:async()=>true});
assert.equal((await failed(event('invitation'))).statusCode,503);
assert.equal((await failed(event('invitation'))).body.includes('secret'),false);
console.log('PASS: employee RPC gateway composes hash protocol, strips private fields, fails closed without limiter');
