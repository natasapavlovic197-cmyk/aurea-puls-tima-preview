'use strict';
const assert=require('node:assert/strict');
const {analyzeItemSeries}=require('./item-aware-trends.cjs');
const row=(weekStart,itemCode,favorablePercent,responseCount=6,itemVersion=1)=>({weekStart,itemCode,favorablePercent,responseCount,itemVersion});
const anchor=analyzeItemSeries([row('2026-11-23','A_WORKLOAD',40),row('2026-11-30','A_WORKLOAD',30)]);
assert.equal(anchor[0].cadence,'weekly');
assert.equal(anchor[0].changePoints,-10);
assert.equal(anchor[0].persistentUnfavorable,true);
const rotating=analyzeItemSeries([row('2026-11-23','R_INFO',40),row('2026-12-21','R_INFO',35)]);
assert.equal(rotating[0].cadence,'four_weekly');
assert.equal(rotating[0].changePoints,-5);
assert.equal(rotating[0].persistentUnfavorable,true);
const gap=analyzeItemSeries([row('2026-11-23','R_INFO',40),row('2026-12-21','R_INFO',20,4),row('2027-01-18','R_INFO',30)]);
assert.equal(gap[0].persistentUnfavorable,false);
assert.equal(gap[0].changePoints,null);
const versioned=analyzeItemSeries([row('2026-11-23','A_WORKLOAD',40),row('2026-11-30','A_WORKLOAD',30,6,2)]);
assert.equal(versioned.length,2);
assert.equal(versioned.every(x=>x.changePoints===null),true);
assert.throws(()=>analyzeItemSeries([row('2026-11-30','R_INFO',50)]),/not scheduled/);
assert.throws(()=>analyzeItemSeries([row('2026-11-23','A_WORKLOAD',40),row('2026-11-23','A_WORKLOAD',40)]),/Duplicate/);
assert.deepEqual(analyzeItemSeries([row('2026-11-23','A_WORKLOAD',30,4)]),[]);
console.log('PASS: item identity, rotation cadence, version isolation, suppression and missing observations');
