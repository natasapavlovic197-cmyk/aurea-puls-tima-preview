'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const original=read('kringle/index.html');
const isolated=read('kringle-andjela-test/index.html');
const patchId='aurea-andjela-no-hologram-test';
assert.ok(original.length>3000000,'Kringle source must be complete');
assert.ok(isolated.length>3000000,'Isolated Anđela test must be complete');
assert.ok(original.includes('portrait-andjela'),'Original Anđela portrait must exist');
assert.ok(isolated.includes('portrait-andjela'),'Isolated Anđela portrait must exist');
assert.ok(!original.includes('id="'+patchId+'"'),'Never patch approved Kringle original');
assert.equal((isolated.match(new RegExp('id="'+patchId+'"','g'))||[]).length,1,'Isolated patch must exist exactly once');
const patch=isolated.match(/<style id="aurea-andjela-no-hologram-test">[\s\S]*?<\/style>/);
assert.ok(patch,'Missing isolated override');
assert.match(patch[0],/background-size:300% 100%!important/,'Three-expression sprite should be preserved');
assert.match(patch[0],/opacity:1!important/,'Do not blend translucent portraits');
assert.match(patch[0],/prefers-reduced-motion/,'Reduced-motion preference must be respected');
assert.equal(isolated.replace(patch[0],''),original,'Isolated page must differ from original only by the isolated Anđela CSS override');
assert.deepEqual(fs.readFileSync(path.join(root,'rukovodilac/index.html')),fs.readFileSync(path.join(root,'locked/manager-v35-approved.html')),'Approved manager UI changed');
assert.deepEqual(fs.readFileSync(path.join(root,'portal/index.html')),fs.readFileSync(path.join(root,'locked/portal-b2b-approved.html')),'Approved portal UI changed');
console.log('PASS: isolated Anđela override only; original Kringle, manager and portal remain unchanged');
